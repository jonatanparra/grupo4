-- =========================================================
-- GLITCH STORE - Modelo relacional (Oracle)
-- USUARIO -> BOLETA -> DETALLE_BOLETA <- PRODUCTO <- CATEGORIA
--
-- La aplicación ejecuta este script automáticamente la primera vez
-- (si la tabla USUARIO no existe). También se puede ejecutar a mano
-- en SQL Developer conectado como GLITCH_STORE.
-- =========================================================

CREATE TABLE CATEGORIA (
    ID          VARCHAR2(40)   CONSTRAINT PK_CATEGORIA PRIMARY KEY,
    NOMBRE      VARCHAR2(60)   NOT NULL CONSTRAINT UK_CATEGORIA_NOMBRE UNIQUE,
    DESCRIPCION VARCHAR2(300),
    IMAGEN      VARCHAR2(300)
);

CREATE TABLE PRODUCTO (
    CODIGO        VARCHAR2(20)   CONSTRAINT PK_PRODUCTO PRIMARY KEY,
    NOMBRE        VARCHAR2(100)  NOT NULL,
    CATEGORIA_ID  VARCHAR2(40)   NOT NULL CONSTRAINT FK_PRODUCTO_CATEGORIA REFERENCES CATEGORIA (ID),
    PRECIO        NUMBER(10)     NOT NULL CONSTRAINT CK_PRODUCTO_PRECIO CHECK (PRECIO >= 0),
    DESCUENTO     NUMBER(3)      DEFAULT 0 NOT NULL CONSTRAINT CK_PRODUCTO_DESCUENTO CHECK (DESCUENTO BETWEEN 0 AND 90),
    STOCK         NUMBER(6)      NOT NULL CONSTRAINT CK_PRODUCTO_STOCK CHECK (STOCK >= 0),
    STOCK_CRITICO NUMBER(6)      CONSTRAINT CK_PRODUCTO_STOCK_CRITICO CHECK (STOCK_CRITICO >= 0),
    DESCRIPCION   VARCHAR2(1000),
    IMAGEN        CLOB
);

CREATE TABLE USUARIO (
    RUN              VARCHAR2(9)    CONSTRAINT PK_USUARIO PRIMARY KEY,
    NOMBRE           VARCHAR2(50)   NOT NULL,
    APELLIDOS        VARCHAR2(100)  NOT NULL,
    CORREO           VARCHAR2(100)  NOT NULL CONSTRAINT UK_USUARIO_CORREO UNIQUE,
    CONTRASENA       VARCHAR2(100)  NOT NULL,
    ROL              VARCHAR2(20)   NOT NULL CONSTRAINT CK_USUARIO_ROL CHECK (ROL IN ('ADMINISTRADOR', 'VENDEDOR', 'CLIENTE')),
    FECHA_NACIMIENTO DATE,
    REGION           VARCHAR2(60),
    COMUNA           VARCHAR2(60),
    DIRECCION        VARCHAR2(300)
);

CREATE SEQUENCE SEQ_BOLETA START WITH 1001 INCREMENT BY 1 NOCACHE;

CREATE TABLE BOLETA (
    ID                VARCHAR2(20)   CONSTRAINT PK_BOLETA PRIMARY KEY,
    USUARIO_RUN       VARCHAR2(9)    CONSTRAINT FK_BOLETA_USUARIO REFERENCES USUARIO (RUN) ON DELETE SET NULL,
    FECHA             TIMESTAMP      NOT NULL,
    ESTADO            VARCHAR2(20)   NOT NULL CONSTRAINT CK_BOLETA_ESTADO CHECK (ESTADO IN ('Pagado', 'Rechazado', 'Enviado', 'Entregado', 'Anulado')),
    MOTIVO_RECHAZO    VARCHAR2(200),
    CLIENTE_NOMBRE    VARCHAR2(50)   NOT NULL,
    CLIENTE_APELLIDOS VARCHAR2(100)  NOT NULL,
    CLIENTE_CORREO    VARCHAR2(100)  NOT NULL,
    TIPO_ENVIO        VARCHAR2(20)   NOT NULL CONSTRAINT CK_BOLETA_TIPO_ENVIO CHECK (TIPO_ENVIO IN ('domicilio', 'retiro')),
    CALLE             VARCHAR2(300),
    DEPARTAMENTO      VARCHAR2(100),
    REGION            VARCHAR2(60),
    COMUNA            VARCHAR2(60),
    INDICACIONES      VARCHAR2(200),
    METODO_PAGO       VARCHAR2(30),
    CUPON             VARCHAR2(20),
    SUBTOTAL          NUMBER(12)     NOT NULL,
    DESCUENTO_CUPON   NUMBER(12)     DEFAULT 0 NOT NULL,
    COSTO_ENVIO       NUMBER(12)     DEFAULT 0 NOT NULL,
    TOTAL             NUMBER(12)     NOT NULL
);

CREATE TABLE DETALLE_BOLETA (
    ID              NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_DETALLE_BOLETA PRIMARY KEY,
    BOLETA_ID       VARCHAR2(20)   NOT NULL CONSTRAINT FK_DETALLE_BOLETA REFERENCES BOLETA (ID) ON DELETE CASCADE,
    PRODUCTO_CODIGO VARCHAR2(20)   CONSTRAINT FK_DETALLE_PRODUCTO REFERENCES PRODUCTO (CODIGO) ON DELETE SET NULL,
    NOMBRE_PRODUCTO VARCHAR2(100)  NOT NULL,
    PRECIO_UNITARIO NUMBER(10)     NOT NULL,
    CANTIDAD        NUMBER(6)      NOT NULL CONSTRAINT CK_DETALLE_CANTIDAD CHECK (CANTIDAD > 0),
    TOTAL_LINEA     NUMBER(12)     NOT NULL
);

CREATE INDEX IX_PRODUCTO_CATEGORIA ON PRODUCTO (CATEGORIA_ID);
CREATE INDEX IX_BOLETA_USUARIO ON BOLETA (USUARIO_RUN);
CREATE INDEX IX_DETALLE_BOLETA ON DETALLE_BOLETA (BOLETA_ID);
